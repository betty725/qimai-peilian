// China's civil day today is UTC+8, independent of the visitor's locale/time zone.
export function todayInChina(instant = new Date()) {
  return new Date(instant.getTime() + 8 * 3600000).toISOString().slice(0,10);
}

function assertDate(iso) {
  if (typeof iso !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(iso) || iso < MIN_DATE || iso > MAX_DATE) {
    throw new RangeError('请选择 1901 至 2100 年内的有效公历日期。');
  }
  const utc = new Date(iso + 'T00:00:00Z');
  if (Number.isNaN(utc.getTime()) || utc.toISOString().slice(0,10) !== iso) {
    throw new RangeError('公历日期无效。');
  }
}

function findTerm(iso) {
  const [year,month,day] = iso.split('-').map(Number);
  const days = calendarRows[year-1901];
  const first = (month-1)*2;
  let index = first;
  if (day < days[first]) index--;
  else if (day >= days[first+1]) index++;
  let startDate;
  if (index < 0) {
    index = 23;
    // Purple Mountain Observatory historical table records the 1900 solstice on Dec 22.
    // https://pmo.cas.cn/xwdt2019/kpdt2019/202203/P020250414456381274062.pdf
    const dec = year === 1901 ? 22 : calendarRows[year-1902][23];
    startDate = (year-1)+'-12-'+String(dec).padStart(2,'0');
  } else {
    const monthOfTerm = Math.floor(index/2)+1;
    startDate = year+'-'+String(monthOfTerm).padStart(2,'0')+'-'+String(days[index]).padStart(2,'0');
  }
  return {...solarTerms[index],startDate};
}

function dayReading(iso) {
  const term = findTerm(iso);
  // Four beginnings: 立春 (2), 立夏 (8), 立秋 (14), 立冬 (20).
  const season = seasons[Math.floor((term.index+22)%24/6)];
  // Six host qi periods, four solar terms each, beginning at 大寒 (1).
  const index = Math.floor((term.index+23)%24/4);
  return {date:iso,term,season,hostQi:{index,...mainQi[index]}};
}

export function getSeasonReading(todayISO, birthISO = '') {
  assertDate(todayISO);
  const today = dayReading(todayISO);
  if (birthISO == null || birthISO === '') return {...today,birth:null};
  assertDate(birthISO);
  if (birthISO > todayISO) throw new RangeError('出生日期不能晚于今天。');
  const birth = dayReading(birthISO);
  const year = Number(birthISO.slice(0,4));
  const majorCold = year+'-01-'+calendarRows[year-1901][1];
  // Convention used in this exhibit: the cultural cycle changes on 大寒 day.
  // 十干配岁运 and the six fixed qi follow 雷丰《时病论·五运六气论》.
  const cycleYear = birthISO < majorCold ? year-1 : year;
  const stemIndex = (cycleYear-4)%10;
  const stemBranch = stems[stemIndex]+branches[(cycleYear-4)%12];
  const movement = movements[stemIndex%5];
  return {...today,birth:{...birth,cycleYear,stemBranch,movement}};
}
